#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md from the real build graph.

Walks every crate that ends up in the Windows `rust-cut-pro` binary (normal +
build dependencies of nle-ui, default features), reads each crate's own
LICENSE/COPYING/NOTICE files from the cargo registry, and writes them grouped
so identical texts appear once.

    python scripts/gen_third_party_notices.py
"""
import collections
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
TARGET = "x86_64-pc-windows-msvc"
# License files that live in a sub-folder of a crate (crate name -> paths).
EXTRA_FILES = {
    "whisper-rs-sys": ["whisper.cpp/LICENSE"],
    "epaint_default_fonts": [
        "fonts/OFL.txt",
        "fonts/UFL.txt",
        "fonts/Hack-Regular.txt",
        "fonts/emoji-icon-font-mit-license.txt",
    ],
}
LICENSE_RE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)", re.I)

# Native code compiled into the binary that cargo metadata cannot describe.
NATIVE = [
    (
        "whisper.cpp / ggml",
        "MIT",
        "https://github.com/ggml-org/whisper.cpp",
        "Speech recognition engine, compiled into the binary through whisper-rs-sys (its MIT text is listed under whisper-rs-sys below).",
    ),
]

FFMPEG_NOTE = """## FFmpeg (not bundled)

Rust Cut Pro does **not** include FFmpeg. It runs `ffmpeg.exe` / `ffprobe.exe`
as separate programs. If you use *Download FFmpeg Automatically*, the editor
downloads the "release essentials" build published by gyan.dev
(<https://www.gyan.dev/ffmpeg/builds/>), verifies its SHA-256 and stores it in
`%LOCALAPPDATA%\\RustCutPro\\bin`. That build is licensed under the
**GNU General Public License v3** (it includes GPL components such as x264 and
x265); its license text is saved beside it as `FFMPEG-LICENSE.txt`, and the
corresponding source code is available from <https://ffmpeg.org/download.html>
and the gyan.dev page above. FFmpeg is a trademark of Fabrice Bellard.
"""


def cargo_json(*args):
    out = subprocess.run(["cargo", *args], cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8").stdout
    return json.loads(out)


def build_graph():
    meta = cargo_json("metadata", "--format-version", "1", "--filter-platform", TARGET)
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ws = set(meta["workspace_members"])
    root = next(i for i in ws if pkgs[i]["name"] == "nle-ui")
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        if cur in seen:
            continue
        seen.add(cur)
        for dep in nodes[cur]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds & {None, "build"}:
                stack.append(dep["pkg"])
    return [pkgs[i] for i in seen if i not in ws]


def license_texts(pkg):
    src = pathlib.Path(pkg["manifest_path"]).parent
    texts = []
    files = sorted(p for p in src.iterdir() if p.is_file() and LICENSE_RE.match(p.name))
    if pkg.get("license_file"):
        lf = (src / pkg["license_file"]).resolve()
        if lf.is_file() and lf not in files:
            files.append(lf)
    for rel in EXTRA_FILES.get(pkg["name"], []):
        if (src / rel).is_file():
            files.append(src / rel)
    for f in files:
        try:
            t = f.read_text(encoding="utf-8", errors="replace").strip()
        except OSError:
            continue
        if t:
            texts.append((f.name, t))
    return texts


def norm(t):
    return hashlib.sha256(" ".join(t.split()).encode()).hexdigest()


def main():
    pkgs = sorted(build_graph(), key=lambda p: (p["name"].lower(), p["version"]))
    groups = collections.OrderedDict()  # text hash -> (text, [crate ids])
    missing = []
    rows = []
    for p in pkgs:
        ident = f'{p["name"]} {p["version"]}'
        lic = p.get("license") or ("see license file" if p.get("license_file") else "UNKNOWN")
        repo = p.get("repository") or p.get("homepage") or f'https://crates.io/crates/{p["name"]}'
        rows.append((p["name"], p["version"], lic, repo))
        texts = license_texts(p)
        if not texts:
            missing.append((ident, lic))
        for _, t in texts:
            h = norm(t)
            groups.setdefault(h, (t, []))[1].append(ident)

    lic_count = collections.Counter(r[2] for r in rows)
    out = []
    w = out.append
    w("# Third-Party Notices\n")
    w("Rust Cut Pro is licensed under MIT OR Apache-2.0 (see `LICENSE-MIT` and `LICENSE-APACHE`).")
    w("It is built on the open-source software listed below. This file is generated by")
    w("`scripts/gen_third_party_notices.py` from the actual Windows build graph — do not edit it by hand.\n")
    w(f"**{len(rows)} Rust crates** and {len(NATIVE)} bundled native library.\n")
    w("| License | Crates |\n|---|---|")
    for k, v in lic_count.most_common():
        w(f"| {k} | {v} |")
    w("")
    w(FFMPEG_NOTE)
    w("## Native libraries compiled in\n")
    for name, lic, url, what in NATIVE:
        w(f"- **{name}** — {lic} — <{url}>. {what}")
    w("")
    w("## Rust crates\n")
    w("| Crate | Version | License | Source |\n|---|---|---|---|")
    for name, ver, lic, repo in rows:
        w(f"| {name} | {ver} | {lic} | <{repo}> |")
    w("")
    if missing:
        w("### Crates that ship no license file\n")
        w("These declare their license only in `Cargo.toml`; the standard text of that license applies.\n")
        for ident, lic in missing:
            w(f"- {ident} — {lic}")
        w("")
    w("## License texts\n")
    w("Each text below is reproduced from the crates listed above it. Identical texts are shown once.\n")
    for i, (text, idents) in enumerate(groups.values(), 1):
        shown = ", ".join(idents)
        w(f"### Text {i} — used by: {shown}\n")
        w("```text")
        w(text.replace("```", "'''"))
        w("```\n")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} — {len(rows)} crates, {len(groups)} distinct license texts, {len(missing)} without a file", file=sys.stderr)


if __name__ == "__main__":
    main()
